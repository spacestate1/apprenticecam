#!/usr/bin/env python3
"""gen_data.py - initial contents of the static data the transliterated engine references (ts_data.c).

  gen_data.py DLL ADDRLIST FUNCSET OUT.c

ADDRLIST: data addresses referenced by ts_gen.c (one hex per line, optional size after a tab).  For each address the
bytes from the DLL file are copied from the address up to the next symbol (decomp/nest/n64dll_syms.txt) or the given
size (at most 4096); base relocations inside a copied range are followed (pointer to data -> its range is copied too and
the pointer is rebased into ts_img; pointer to code -> the port's function FUN_<addr> when in FUNCSET, else a stub
that stops with NOT PORTED).  Zero bytes are not emitted (ts_img is zero-initialised like the .bss)."""
import sys, struct, re, bisect

DLL, ALIST, FSET, OUT = sys.argv[1:5]
SYMS = '<repo>/decomp/nest/n64dll_syms.txt'
d = open(DLL, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]; optsz = struct.unpack_from('<H', d, pe + 20)[0]
base = struct.unpack_from('<Q', d, pe + 24 + 24)[0]
secs = []
for i in range(nsec):
    o = pe + 24 + optsz + 40 * i
    name = d[o:o + 8].rstrip(b'\0').decode()
    vsz, va, rsz, roff = struct.unpack_from('<IIII', d, o + 8)
    secs.append((name, base + va, vsz, rsz, roff))
def fbyte(a):
    for n, va, vsz, rsz, roff in secs:
        if va <= a < va + vsz:
            return d[roff + a - va] if a - va < rsz else 0
    return None
def is_code(a):
    for n, va, vsz, rsz, roff in secs:
        if va <= a < va + vsz: return n in ('.text', 'text')
    return False
# base relocations (DIR64)
dd_reloc = struct.unpack_from('<II', d, pe + 24 + 112 + 5 * 8)
rva, size = dd_reloc
def rva2off(r):
    for n, va, vsz, rsz, roff in secs:
        if va - base <= r < va - base + max(vsz, rsz): return roff + r - (va - base)
relocs = set()
o = rva2off(rva); end = o + size
while o < end:
    page, bsz = struct.unpack_from('<II', d, o)
    if bsz == 0: break
    for k in range((bsz - 8) // 2):
        e = struct.unpack_from('<H', d, o + 8 + 2 * k)[0]
        if e >> 12 == 10: relocs.add(base + page + (e & 0xfff))
    o += bsz
LO, HI = 0x180261000, 0x180508000
syms = sorted(set(int(l.split('\t')[0], 16) for l in open(SYMS) if re.match(r'^[0-9a-f]{9}\t', l)))
funcset = set(int(l.split('#')[0].strip(), 16) for l in open(FSET) if l.split('#')[0].strip())
work = []
for l in open(ALIST):
    p = l.split()
    if p: work.append((int(p[0], 16), int(p[1]) if len(p) > 1 else 0))
# the whole initialised .data (tables in it are indexed at run time, e.g. the error table DAT_1802932f0 L42204)
for n_, va_, vsz_, rsz_, roff_ in secs:
    if n_ == '.data': work.append((va_, min(vsz_, rsz_)))
done = {}; codeptrs = {}; dataptrs = {}
while work:
    a, sz = work.pop()
    if not (LO <= a < HI): continue
    i = bisect.bisect_right(syms, a)
    nxt = syms[i] if i < len(syms) else a + 8
    n = max(sz, nxt - a, 8)
    if sz == 0: n = min(n, 4096)
    # a string runs to its terminating NUL
    k = 0
    while k < 4096 and fbyte(a + k): k += 1
    n = max(n, k + 1)
    if a in done and done[a] >= n: continue
    done[a] = n
    for x in range(a, a + n):
        if x in relocs:
            v = struct.unpack('<Q', bytes(fbyte(x + k) or 0 for k in range(8)))[0]
            if is_code(v): codeptrs[x] = v
            elif LO <= v < HI: dataptrs[x] = v; work.append((v, 0))
# merge ranges and emit
ranges = sorted(done.items())
merged = []
for a, n in ranges:
    if merged and a <= merged[-1][0] + merged[-1][1]:
        e = max(merged[-1][0] + merged[-1][1], a + n); merged[-1][1] = e - merged[-1][0]
    else: merged.append([a, n])
with open(OUT, 'w') as f:
    f.write('/* generated by viewer/nest/ts/gen/gen_data.py from n64dll.dll - initial static data referenced by ts_gen.c */\n')
    f.write('#include "ts_gen.h"\n\n')
    stubs = sorted(set(v for v in codeptrs.values() if v not in funcset))
    for v in sorted(set(codeptrs.values())):
        if v in funcset: f.write('extern char FUN_%x_sym[] __asm__("FUN_%x");\n' % (v, v))
    for v in stubs:
        f.write('static void ts_stub_%x(void) { ts_not_ported(0x%xULL); }\n' % (v, v))
    nb = 0
    f.write('static const struct { uint64_t a; uint16_t n; const char *b; } ts_init_bytes[] = {\n')
    for a, n in merged:
        bs = bytes(fbyte(x) or 0 for x in range(a, a + n))
        # skip pointer slots (filled below) and all-zero runs
        k = 0
        while k < n:
            if bs[k] == 0: k += 1; continue
            j = k
            while j < n and (bs[j] != 0 or (j + 1 < n and bs[j + 1] != 0)) and j - k < 2000: j += 1
            f.write('  {0x%xULL, %d, "%s"},\n' % (a + k, j - k, ''.join('\\x%02x' % c for c in bs[k:j])))
            nb += j - k; k = j
    f.write('  {0, 0, 0}};\n')
    f.write('static const struct { uint64_t at, to; } ts_data_ptrs[] = {\n')
    for x, v in sorted(dataptrs.items()): f.write('  {0x%xULL, 0x%xULL},\n' % (x, v))
    f.write('  {0, 0}};\n')
    f.write('void ts_img_init(void) {\n  memset(ts_img, 0, sizeof ts_img);\n')
    f.write('  for (int i = 0; ts_init_bytes[i].a; i++) memcpy(ts_img + (ts_init_bytes[i].a - TS_IMG_LO), ts_init_bytes[i].b, ts_init_bytes[i].n);\n')
    f.write('  for (int i = 0; ts_data_ptrs[i].at; i++) TS_G(void *, ts_data_ptrs[i].at) = ts_img + (ts_data_ptrs[i].to - TS_IMG_LO);\n')
    for x, v in sorted(codeptrs.items()):
        if v in funcset: f.write('  TS_G(void *, 0x%xULL) = (void *)FUN_%x_sym;\n' % (x, v))
        else: f.write('  TS_G(void *, 0x%xULL) = (void *)ts_stub_%x;\n' % (x, v))
    f.write('}\n')
print('data: %d ranges, %d bytes, %d data ptrs, %d code ptrs (%d stubs)' % (len(merged), nb, len(dataptrs), len(codeptrs), len(stubs)), file=sys.stderr)
